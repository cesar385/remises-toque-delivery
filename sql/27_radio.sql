-- ===================== Radio (PTT) entre la central y los móviles =====================
-- El audio se guarda en la base y por tiempo real solo viaja un aviso corto con el número de mensaje.
-- Así no se pierde por el límite de tamaño del tiempo real y funciona igual en la app Android y en el navegador.
create table if not exists rodar.radio_msgs (
  id bigint generated by default as identity primary key,
  de text, movil_id bigint, usuario_id bigint, mime text, audio text, creado timestamp default now()
);
create index if not exists ix_radio_creado on rodar.radio_msgs(creado);
revoke all on rodar.radio_msgs from anon, authenticated;

create or replace function public.r_radio_enviar(p_token text default null, p_q jsonb default '{}', p_b jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = rodar, public, extensions as $$
declare u rodar.usuarios := rodar.usuario(p_token); s rodar.sesiones; a text := p_b ->> 'audio'; nid bigint; m rodar.moviles;
begin
  if coalesce(a, '') !~ '^data:audio/' then raise exception 'Audio inválido'; end if;
  if length(a) > 1500000 then raise exception 'El mensaje es demasiado largo (máximo 30 segundos)'; end if;
  select * into s from rodar.sesiones where token = p_token;
  if s.movil_id is not null then select * into m from rodar.moviles where id = s.movil_id; end if;
  -- los audios viejos se vacían (quedan solo los de la última hora)
  update rodar.radio_msgs set audio = null where audio is not null and creado < now() - interval '1 hour';
  insert into rodar.radio_msgs(de, movil_id, usuario_id, mime, audio)
  values (coalesce(nullif(left(p_b ->> 'de', 120), ''), case when m.id is not null then 'Móvil ' || m.numero else trim(u.nombre || ' ' || coalesce(u.apellido, '')) end),
          m.id, u.id, left(p_b ->> 'mime', 60), a) returning id into nid;
  perform rodar.emit('radio', 'radio', jsonb_build_object('id', nid, 'de', (select de from rodar.radio_msgs where id = nid), 'movil', m.numero, 'clave', left(p_b ->> 'clave', 40)));
  return jsonb_build_object('ok', true, 'id', nid);
end $$;

create or replace function public.r_radio_audio(p_token text default null, p_q jsonb default '{}', p_b jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = rodar, public, extensions as $$
declare u rodar.usuarios := rodar.usuario(p_token); r rodar.radio_msgs;
begin
  select * into r from rodar.radio_msgs where id = (p_q ->> 'id')::bigint;
  if r.id is null or r.audio is null then raise exception 'El audio ya no está disponible'; end if;
  return jsonb_build_object('id', r.id, 'de', r.de, 'mime', r.mime, 'audio', r.audio);
end $$;

grant execute on function public.r_radio_enviar(text, jsonb, jsonb), public.r_radio_audio(text, jsonb, jsonb) to anon, authenticated;
notify pgrst, 'reload schema';
