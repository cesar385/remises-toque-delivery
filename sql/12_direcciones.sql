-- Direcciones aprendidas: el mapa libre (OpenStreetMap) no tiene la numeración de muchas calles de Federal.
-- El sistema aprende la ubicación real de cada "calle + altura" con el GPS del chofer (al tocar "Llegué" y al finalizar)
-- y con eso ubica las direcciones repetidas y estima las alturas intermedias de la misma calle.
create table if not exists rodar.direcciones_conocidas (
  id bigint generated by default as identity primary key,
  calle text not null, calle_norm text not null, altura int not null, localidad text,
  lat double precision not null, lng double precision not null, usos int default 1, actualizado timestamp
);
create unique index if not exists ux_dir_conocida on rodar.direcciones_conocidas(calle_norm, altura);
create index if not exists ix_dir_conocida_calle on rodar.direcciones_conocidas(calle_norm);

create or replace function rodar.norm_calle(t text) returns text language sql immutable as $$
  select nullif(trim(regexp_replace(regexp_replace(regexp_replace(translate(lower(coalesce(t, '')), 'áéíóúüñ', 'aeiouun'),
    '^(calle|avenida|av\.?|bv\.?|bvard\.?|boulevard|pje\.?|pasaje|diagonal|diag\.?)\s+', ''), '[^a-z0-9 ]', ' ', 'g'), '\s+', ' ', 'g')), '')
$$;

-- "San Martín 450, Federal" -> calle "San Martín", altura 450 ("25 de Mayo 300" -> "25 de Mayo", 300)
create or replace function rodar.separar_dir(d text, out calle text, out altura int) language plpgsql immutable as $$
declare m text[]; base text := trim(split_part(coalesce(d, ''), ',', 1));
begin
  m := regexp_match(base, '^(.+?)\s+(?:n(?:ro|°|º)?\.?\s*)?(\d{1,5})$', 'i');
  if m is null then calle := nullif(base, ''); altura := null; else calle := trim(m[1]); altura := m[2]::int; end if;
end $$;

create or replace function rodar.aprender_dir(p_dir text, p_lat float8, p_lng float8, p_loc text) returns void language plpgsql as $$
declare s record; cn text;
begin
  if p_lat is null or p_lng is null then return; end if;
  s := rodar.separar_dir(p_dir); cn := rodar.norm_calle(s.calle);
  if s.altura is null or s.altura <= 0 or cn is null then return; end if;
  insert into rodar.direcciones_conocidas(calle, calle_norm, altura, localidad, lat, lng, usos, actualizado)
  values (s.calle, cn, s.altura, p_loc, p_lat, p_lng, 1, rodar.ahora())
  on conflict (calle_norm, altura) do update set
    lat = (rodar.direcciones_conocidas.lat * least(rodar.direcciones_conocidas.usos, 9) + excluded.lat) / (least(rodar.direcciones_conocidas.usos, 9) + 1),
    lng = (rodar.direcciones_conocidas.lng * least(rodar.direcciones_conocidas.usos, 9) + excluded.lng) / (least(rodar.direcciones_conocidas.usos, 9) + 1),
    usos = rodar.direcciones_conocidas.usos + 1, actualizado = excluded.actualizado;
end $$;

-- aprende con el GPS real del móvil (no con móviles simulados)
create or replace function rodar.trg_aprender_dir() returns trigger language plpgsql as $$
declare m rodar.moviles;
begin
  begin
    select * into m from rodar.moviles where id = new.movil_id;
    if not found or m.simulado or m.lat is null then return new; end if;
    if new.llegada_at is not null and old.llegada_at is null
       and (new.origen_lat is null or rodar.dist(m.lat, m.lng, new.origen_lat, new.origen_lng) < 600) then
      perform rodar.aprender_dir(new.origen_dir, m.lat, m.lng, new.origen_loc);
    end if;
    if new.estado = 'finalizado' and old.estado is distinct from 'finalizado' and new.destino_dir is not null then
      perform rodar.aprender_dir(new.destino_dir, m.lat, m.lng, new.destino_loc);
    end if;
  exception when others then null; -- nunca frena un viaje
  end;
  return new;
end $$;
create or replace trigger viajes_aprender_dir after update of llegada_at, estado on rodar.viajes for each row execute function rodar.trg_aprender_dir();

-- búsqueda: exacta, interpolada entre dos alturas conocidas de la misma calle, o la más cercana
create or replace function public.r_dir_buscar(p_token text default null, p_q jsonb default '{}', p_b jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = rodar, public, extensions as $$
declare s record; cn text; a rodar.direcciones_conocidas; b rodar.direcciones_conocidas; f float8;
begin
  s := rodar.separar_dir(p_q ->> 'q'); cn := rodar.norm_calle(s.calle);
  if cn is null or s.altura is null then return 'null'; end if;
  select * into a from rodar.direcciones_conocidas where calle_norm = cn and altura <= s.altura order by altura desc limit 1;
  select * into b from rodar.direcciones_conocidas where calle_norm = cn and altura >= s.altura order by altura limit 1;
  if a.id is not null and a.altura = s.altura then
    return jsonb_build_object('calle', a.calle, 'altura', s.altura, 'lat', a.lat, 'lng', a.lng, 'localidad', a.localidad, 'precision', 'exacta');
  end if;
  if a.id is not null and b.id is not null and b.altura - a.altura <= 1500 then
    f := (s.altura - a.altura)::float8 / nullif(b.altura - a.altura, 0);
    return jsonb_build_object('calle', a.calle, 'altura', s.altura, 'lat', a.lat + (b.lat - a.lat) * f, 'lng', a.lng + (b.lng - a.lng) * f, 'localidad', a.localidad, 'precision', 'estimada');
  end if;
  a := coalesce(a, b);
  if a.id is null then select * into a from rodar.direcciones_conocidas where calle_norm = cn order by abs(altura - s.altura) limit 1; end if;
  if a.id is not null and abs(a.altura - s.altura) <= 200 then
    return jsonb_build_object('calle', a.calle, 'altura', s.altura, 'lat', a.lat, 'lng', a.lng, 'localidad', a.localidad, 'precision', 'cercana');
  end if;
  return 'null';
end $$;

-- al tocar el mapa: dirección conocida más cercana (para sugerir la altura)
create or replace function public.r_dir_cercana(p_token text default null, p_q jsonb default '{}', p_b jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = rodar, public, extensions as $$
declare lat float8 := (p_q ->> 'lat')::float8; lng float8 := (p_q ->> 'lng')::float8; d rodar.direcciones_conocidas; dist float8;
begin
  if lat is null or lng is null then return 'null'; end if;
  select x.* into d from rodar.direcciones_conocidas x
  where x.lat between lat - 0.002 and lat + 0.002 and x.lng between lng - 0.0025 and lng + 0.0025
  order by rodar.dist(x.lat, x.lng, lat, lng) limit 1;
  if d.id is null then return 'null'; end if;
  dist := rodar.dist(d.lat, d.lng, lat, lng);
  if dist > 70 then return 'null'; end if;
  return jsonb_build_object('calle', d.calle, 'altura', d.altura, 'localidad', d.localidad, 'metros', round(dist::numeric));
end $$;

grant execute on function public.r_dir_buscar(text, jsonb, jsonb), public.r_dir_cercana(text, jsonb, jsonb) to anon, authenticated;
revoke all on rodar.direcciones_conocidas from anon, authenticated;
alter function rodar.norm_calle(text) set search_path = rodar, public, extensions;
alter function rodar.separar_dir(text) set search_path = rodar, public, extensions;
alter function rodar.aprender_dir(text, float8, float8, text) set search_path = rodar, public, extensions;
alter function rodar.trg_aprender_dir() set search_path = rodar, public, extensions;

-- punto de partida: las direcciones con altura de los viajes reales ya terminados (con GPS del chofer al llegar)
do $$ declare v record; begin
  for v in select vj.origen_dir, vj.origen_loc, p.lat, p.lng from rodar.viajes vj join rodar.moviles m on m.id = vj.movil_id and not m.simulado
    join lateral (select lat, lng from rodar.posiciones where movil_id = vj.movil_id and ts between vj.llegada_at - interval '20 seconds' and vj.llegada_at + interval '20 seconds' order by abs(extract(epoch from ts - vj.llegada_at)) limit 1) p on true
    where vj.llegada_at is not null loop
    perform rodar.aprender_dir(v.origen_dir, v.lat, v.lng, v.origen_loc);
  end loop;
end $$;
