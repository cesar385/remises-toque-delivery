-- =====================================================================
-- Remises TOQUE! — esquema para Supabase (Postgres)
-- Todas las tablas viven en el esquema "rodar" (NO expuesto por la API REST).
-- Solo se exponen funciones del esquema public (RPC) que validan la sesión.
-- =====================================================================
create schema if not exists extensions;
create extension if not exists pgcrypto schema extensions;
create schema if not exists rodar;
revoke all on schema rodar from public;

create table if not exists rodar.config (clave text primary key, valor jsonb);

create table if not exists rodar.usuarios (
  id bigint generated by default as identity primary key,
  documento text unique not null, usuario text unique,
  nombre text not null, apellido text default '',
  email text, telefono text, email_recupero text, tel_recupero text, cbu text, alias_bancario text,
  password_hash text not null,
  roles text not null default 'operador',
  habilitado boolean not null default true,
  foto text, corporativo_id bigint, licencia_vence date, docs text default '[]',
  creado timestamp default (now() at time zone 'America/Argentina/Buenos_Aires')
);

create table if not exists rodar.corporativos (
  id bigint generated by default as identity primary key, nombre text not null, cuit text, centro_costo text,
  contacto text, telefono text, activo boolean default true
);

create table if not exists rodar.planes (
  id bigint generated by default as identity primary key, descripcion text not null,
  modo_pago text not null default 'prepago', modo_cobro text not null default 'fijo',
  tipo1 boolean default false, vencer_saldo boolean default false,
  monto_fijo numeric default 0, monto_viaje numeric default 0, pct_viaje numeric default 0,
  periodicidad text default 'mensual', dia_semana int default 1, dia_mes int default 1, hora_cobro int default 0,
  horas_bloqueo int default 48, minimo numeric default 0, sistema boolean default false
);

create table if not exists rodar.zonas (
  id bigint generated by default as identity primary key, nombre text not null,
  poligono jsonb not null default '[]', color text default '#1f8a8a',
  parada_lat double precision, parada_lng double precision, es_parada boolean default true, orden int default 0
);

create table if not exists rodar.zonas_peligrosas (
  id bigint generated by default as identity primary key, nombre text, poligono jsonb not null, creado timestamp
);

create table if not exists rodar.moviles (
  id bigint generated by default as identity primary key,
  numero int unique not null, patente text, licencia text, marca text, modelo text, anio int, color text,
  titular_id bigint references rodar.usuarios(id),
  tarifador boolean default true, exigir_obd boolean default false, habilitado boolean default true,
  plan_id bigint references rodar.planes(id), prorroga_hasta timestamp,
  estado text default 'desconectado',
  conductor_id bigint references rodar.usuarios(id),
  lat double precision, lng double precision, rumbo double precision, velocidad double precision,
  parada_id bigint, parada_ingreso timestamp, ultima_senal timestamp, simulado boolean default false,
  docs text default '[]'
);

create table if not exists rodar.movil_conductores (
  movil_id bigint references rodar.moviles(id) on delete cascade,
  usuario_id bigint references rodar.usuarios(id) on delete cascade,
  primary key (movil_id, usuario_id)
);

create table if not exists rodar.clientes (
  id bigint generated by default as identity primary key,
  telefono text unique not null, alias text, notas text,
  bloqueado boolean default false, motivo_bloqueo text, bloqueado_por bigint, bloqueado_at timestamp,
  baja_at timestamp, baja_por bigint, corporativo_id bigint, creado timestamp
);

create table if not exists rodar.cliente_domicilios (
  id bigint generated by default as identity primary key, cliente_id bigint references rodar.clientes(id) on delete cascade,
  direccion text, localidad text, provincia text, referencias text, lat double precision, lng double precision,
  usos int default 1, ultimo_uso timestamp
);

create table if not exists rodar.negativos (
  cliente_id bigint references rodar.clientes(id) on delete cascade,
  movil_id bigint references rodar.moviles(id) on delete cascade,
  creado timestamp, usuario_id bigint, primary key (cliente_id, movil_id)
);

create table if not exists rodar.viajes (
  id bigint generated by default as identity primary key,
  cliente_id bigint references rodar.clientes(id) on delete set null, telefono text, alias text,
  origen_dir text, origen_loc text, origen_prov text, origen_ref text, origen_lat double precision, origen_lng double precision,
  destino_dir text, destino_loc text, destino_prov text, destino_ref text, destino_lat double precision, destino_lng double precision,
  datos_movil text, canal text default 'centralita', origen_tipo text default 'central', estado text default 'pendiente',
  movil_id bigint, conductor_id bigint, operador_id bigint, zona_id bigint, parada_id bigint,
  creado timestamp, programado timestamp, asignado_at timestamp, llegada_at timestamp, inicio_at timestamp, fin_at timestamp,
  anulado_at timestamp, motivo_anulacion text,
  monto numeric, monto_estimado numeric, km numeric, minutos numeric, espera_min numeric,
  medio_pago text default 'efectivo', a_oferta boolean default false, pin text, pin_requerido boolean default false,
  cantidad_moviles int default 1, calificacion int, corporativo_id bigint, tarifa_id bigint, indice numeric default 1,
  intentos int default 0, rechazos bigint[] default '{}', grupo text, oferta_expira timestamptz
);
create index if not exists ix_viajes_estado on rodar.viajes(estado);
create index if not exists ix_viajes_creado on rodar.viajes(creado);

create table if not exists rodar.tarifas (
  id bigint generated by default as identity primary key, orden int default 1, nombre text not null,
  tipo text default 'fija', activa boolean default true, bajada numeric default 0, suba_max numeric default 30, baja_max numeric default 0,
  con_espera boolean default true, espera_seg int default 60, precio_ficha numeric default 0, cortesia_mts int default 0, cortesia_min int default 0,
  dias text default '[1,2,3,4,5,6,0]', feriado boolean default true, hora_desde text default '00:00', hora_hasta text default '23:59',
  redondeo_mts int default 100, ficha_mts int default 100
);

create table if not exists rodar.feriados (id bigint generated by default as identity primary key, fecha date unique, descripcion text);

create table if not exists rodar.cuenta_movimientos (
  id bigint generated by default as identity primary key, movil_id bigint references rodar.moviles(id) on delete cascade,
  fecha timestamp, tipo text, monto numeric, detalle text, usuario_id bigint, viaje_id bigint
);
create index if not exists ix_cm on rodar.cuenta_movimientos(movil_id);

create table if not exists rodar.penalizaciones (
  id bigint generated by default as identity primary key, movil_id bigint references rodar.moviles(id) on delete cascade,
  hasta timestamp, usuario_id bigint, motivo text, creado timestamp
);

create table if not exists rodar.solicitudes_conductor (
  id bigint generated by default as identity primary key, estado text default 'pendiente',
  nombre text, apellido text, dni text, telefono text, email text, patente text, marca text, modelo text, anio int,
  origen text default 'web', docs text default '[]', observacion text, fecha timestamp
);

create table if not exists rodar.canales (codigo text primary key, nombre text, promo boolean default false, exigir_pin boolean default false, cobro_modo text default 'tarifado', ajuste_pct int default 0, orden int);
create table if not exists rodar.medios_pago (codigo text primary key, nombre text, habilitado boolean default true, ajuste_pct int default 0, aplica_promo boolean default false, orden int);

create table if not exists rodar.mp_pagos (
  id bigint generated by default as identity primary key, tipo text, movil_id bigint, viaje_id bigint, monto numeric, comision numeric default 0,
  estado text default 'pendiente', acreditado boolean default false, medio text, liberacion date, mp_id text, fecha timestamp, rendido boolean default false
);
create table if not exists rodar.mp_saldo_mov (id bigint generated by default as identity primary key, movil_id bigint, fecha timestamp, tipo text, monto numeric, detalle text);

create table if not exists rodar.autoridades (id bigint generated by default as identity primary key, nombre text, cargo text, organismo text, direccion text, email text);
create table if not exists rodar.docs_generados (id bigint generated by default as identity primary key, tipo text, autoridad text, usuario_id bigint, fecha timestamp);

create table if not exists rodar.acciones_usuarios (id bigint generated by default as identity primary key, fecha timestamp, actor_id bigint, actor text, tipo text, afectado text, detalle text);
create table if not exists rodar.eventos_moviles (id bigint generated by default as identity primary key, fecha timestamp, movil_id bigint, movil_numero int, tipo text, ref text, detalle text);
create index if not exists ix_evm on rodar.eventos_moviles(fecha);

create table if not exists rodar.sesiones (
  token text primary key, usuario_id bigint, tipo text default 'web', movil_id bigint,
  inicio timestamp, ultimo timestamp, ip text, activa boolean default true, cooldown_hasta timestamp
);
create table if not exists rodar.conexion_diaria (usuario_id bigint, fecha date, segundos int default 0, cargados int default 0, tipo text, primary key (usuario_id, fecha, tipo));

create table if not exists rodar.posiciones (id bigint generated by default as identity primary key, movil_id bigint, ts timestamp, lat double precision, lng double precision, estado text, velocidad double precision);
create index if not exists ix_pos on rodar.posiciones(movil_id, ts);

create table if not exists rodar.soporte_conv (id bigint generated by default as identity primary key, tipo text, movil_id bigint, cliente_tel text, cliente_alias text, asunto text, no_leidos int default 0, cerrada boolean default false, actualizado timestamp);
create table if not exists rodar.soporte_msg (id bigint generated by default as identity primary key, conv_id bigint references rodar.soporte_conv(id) on delete cascade, de text, texto text, fecha timestamp);
create table if not exists rodar.chat_conv (id bigint generated by default as identity primary key, canal text, telefono text, alias text, estado text default 'abierta', no_leidos int default 0, actualizado timestamp);
create table if not exists rodar.chat_msg (id bigint generated by default as identity primary key, conv_id bigint references rodar.chat_conv(id) on delete cascade, de text, texto text, fecha timestamp);

create table if not exists rodar.reportes (id bigint generated by default as identity primary key, usuario_id bigint, titulo text, descripcion text, pantalla text, estado text default 'abierto', fecha timestamp);
create table if not exists rodar.reporte_historial (id bigint generated by default as identity primary key, reporte_id bigint, de text, texto text, estado text, fecha timestamp);

create table if not exists rodar.novedades (id bigint generated by default as identity primary key, seccion text default 'semana', etiqueta text, titulo text, cuerpo text, fecha date, alerta text);
create table if not exists rodar.novedades_vistas (usuario_id bigint, novedad_id bigint, primary key(usuario_id, novedad_id));

create table if not exists rodar.modulos (codigo text primary key, nombre text, descripcion text, precio numeric, unidad text, obligatorio boolean default false, activo boolean default true, cantidad int default 1, activo_prox boolean);
create table if not exists rodar.moviles_historial (id bigint generated by default as identity primary key, fecha timestamp, movil_id bigint, movil_numero int, tipo text, entidad text, usuario text, detalle text);
create table if not exists rodar.mensajes_flota (id bigint generated by default as identity primary key, texto text, usuario_id bigint, fecha timestamp);
create table if not exists rodar.limite_pedidos (clave text, ts timestamptz default now());
