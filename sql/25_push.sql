-- ===================== Notificaciones push para la app del conductor =====================
-- Con el celular bloqueado o la app cerrada, el navegador no recibe el tiempo real. Las notificaciones push sí llegan:
-- la base encola el aviso y llama a la Edge Function "push" (con pg_net), que lo entrega a cada celular suscripto.
-- Las claves VAPID y el secreto se guardan en rodar.config ('push'); nunca se publican en este archivo.
create extension if not exists pg_net;

create table if not exists rodar.push_subs (
  id bigint generated by default as identity primary key,
  endpoint text not null unique, p256dh text not null, auth text not null,
  token text, movil_id bigint, usuario_id bigint, ua text,
  activa boolean default true, creado timestamp, actualizado timestamp
);
create index if not exists ix_push_subs_movil on rodar.push_subs(movil_id) where activa;

create table if not exists rodar.push_cola (
  id bigint generated by default as identity primary key,
  clave text, msg jsonb, subs jsonb, estado text default 'pendiente', resultado jsonb, creado timestamp default now()
);
create index if not exists ix_push_cola_clave on rodar.push_cola(clave, creado);
revoke all on rodar.push_subs, rodar.push_cola from anon, authenticated;

-- Encola y dispara un aviso. p_subs: lista de suscripciones; p_clave evita repetir el mismo aviso (ej. oferta abierta).
create or replace function rodar.push_enviar(p_subs jsonb, p_msg jsonb, p_clave text default null) returns void language plpgsql as $$
declare c jsonb := rodar.cfg('push', '{}'); nid bigint;
begin
  if coalesce(c ->> 'url', '') = '' or coalesce(c ->> 'privada', '') = '' then return; end if;
  if p_subs is null or jsonb_array_length(p_subs) = 0 then return; end if;
  if p_clave is not null and exists(select 1 from rodar.push_cola where clave = p_clave and creado > now() - interval '15 minutes') then return; end if;
  insert into rodar.push_cola(clave, msg, subs) values (p_clave, p_msg, p_subs) returning id into nid;
  perform net.http_post(url := c ->> 'url', body := jsonb_build_object('id', nid),
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-push-secreto', c ->> 'secreto'), timeout_milliseconds := 8000);
exception when others then null; -- un aviso que falla nunca frena la operación
end $$;

-- Suscripciones vigentes de un móvil (solo celulares con la sesión abierta)
create or replace function rodar.push_subs_movil(p_movil bigint) returns jsonb language sql stable as $$
  select coalesce(jsonb_agg(jsonb_build_object('endpoint', p.endpoint, 'p256dh', p.p256dh, 'auth', p.auth)), '[]'::jsonb)
  from rodar.push_subs p join rodar.sesiones s on s.token = p.token and s.activa
  where p.activa and p.movil_id = p_movil
$$;
create or replace function rodar.push_subs_flota() returns jsonb language sql stable as $$
  select coalesce(jsonb_agg(jsonb_build_object('endpoint', p.endpoint, 'p256dh', p.p256dh, 'auth', p.auth)), '[]'::jsonb)
  from rodar.push_subs p join rodar.sesiones s on s.token = p.token and s.activa where p.activa
$$;

-- Traduce los eventos del tiempo real que le importan al conductor en un aviso push
create or replace function rodar.push_evento(p_topic text, p_evento text, p_payload jsonb) returns void language plpgsql as $$
declare mid bigint; subs jsonb; msg jsonb; clave text; d jsonb := coalesce(p_payload, '{}');
  pesos text := case when (d ->> 'monto_estimado') is not null then ' · $ ' || replace(to_char(round((d ->> 'monto_estimado')::numeric), 'FM999G999G999'), ',', '.') else '' end;
begin
  if p_topic = 'flota' and p_evento = 'mensaje_flota' then
    subs := rodar.push_subs_flota();
    msg := jsonb_build_object('tipo', 'flota', 'titulo', '📢 Mensaje de la central', 'cuerpo', d ->> 'texto', 'url', 'conductor.html#mensaje', 'tag', 'rodar-flota', 'ttl', 86400, 'fijo', true);
    perform rodar.push_enviar(subs, msg); return;
  end if;
  if p_topic !~ '^movil-\d+$' or p_evento not in ('oferta', 'oferta_abierta', 'oferta_cancelada', 'asignado', 'mensaje') then return; end if;
  mid := substr(p_topic, 7)::bigint;
  if not exists(select 1 from rodar.push_subs where movil_id = mid and activa) then return; end if;
  subs := rodar.push_subs_movil(mid);
  msg := case p_evento
    when 'oferta' then jsonb_build_object('tipo', 'oferta', 'titulo', '🚕 Nuevo viaje #' || (d ->> 'id'), 'cuerpo', coalesce(d ->> 'origen_dir', '') || coalesce(' → ' || (d ->> 'destino_dir'), '') || pesos || E'\nTocá para aceptarlo',
      'url', 'conductor.html#oferta', 'tag', 'rodar-oferta', 'ttl', greatest(10, coalesce((d ->> 'segundos')::int, 20)), 'fijo', true, 'viaje', d ->> 'id')
    when 'oferta_abierta' then jsonb_build_object('tipo', 'oferta', 'titulo', '📣 Viaje a oferta #' || (d ->> 'id'), 'cuerpo', coalesce(d ->> 'origen_dir', '') || pesos || E'\nTocá para postularte',
      'url', 'conductor.html#oferta', 'tag', 'rodar-abierta-' || (d ->> 'id'), 'ttl', 60, 'viaje', d ->> 'id')
    when 'oferta_cancelada' then jsonb_build_object('tipo', 'cerrar', 'cerrar', 'rodar-oferta', 'titulo', 'Viaje reasignado', 'cuerpo', 'El viaje ofrecido ya no está disponible', 'tag', 'rodar-oferta', 'ttl', 30, 'silencio', true, 'url', 'conductor.html')
    when 'asignado' then jsonb_build_object('tipo', 'asignado', 'titulo', '✅ Te asignaron un viaje', 'cuerpo', 'La central te asignó el viaje #' || coalesce(d ->> 'id', '') || E'\nTocá para ver a dónde ir', 'url', 'conductor.html', 'tag', 'rodar-asignado', 'ttl', 600, 'fijo', true)
    when 'mensaje' then jsonb_build_object('tipo', 'mensaje', 'titulo', '💬 Mensaje de la ' || coalesce(d ->> 'de', 'Central'), 'cuerpo', coalesce(d ->> 'texto', '') || E'\nTocá para responder', 'url', 'conductor.html#soporte', 'tag', 'rodar-soporte', 'ttl', 86400, 'fijo', true)
  end;
  clave := case when p_evento = 'oferta_abierta' then 'abierta-' || (d ->> 'id') || '-' || mid end;
  perform rodar.push_enviar(subs, msg, clave);
exception when others then null;
end $$;

-- El emisor del tiempo real ahora también dispara los avisos push
create or replace function rodar.emit(p_topic text, p_evento text, p_payload jsonb) returns void language plpgsql as $$
begin
  begin
    perform realtime.send(coalesce(p_payload, '{}'::jsonb), p_evento, rodar.topico(p_topic), false);
  exception when others then null; -- sin Realtime disponible: se ignora (los clientes también consultan periódicamente)
  end;
  if p_evento in ('oferta', 'oferta_abierta', 'oferta_cancelada', 'asignado', 'mensaje', 'mensaje_flota') then
    perform rodar.push_evento(p_topic, p_evento, p_payload);
  end if;
end $$;

-- App del conductor: clave pública y alta de la suscripción de este celular
create or replace function public.r_cond_push(p_token text default null, p_q jsonb default '{}', p_b jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = rodar, public, extensions as $$
declare m rodar.moviles := rodar.movil_sesion(p_token); u rodar.usuarios := rodar.usuario(p_token); s jsonb := p_b -> 'sub'; c jsonb := rodar.cfg('push', '{}');
begin
  if s is null then return jsonb_build_object('publica', c ->> 'publica'); end if;
  if coalesce(s ->> 'endpoint', '') !~ '^https://' or coalesce(s #>> '{keys,p256dh}', '') = '' or coalesce(s #>> '{keys,auth}', '') = '' then raise exception 'Suscripción inválida'; end if;
  insert into rodar.push_subs(endpoint, p256dh, auth, token, movil_id, usuario_id, ua, activa, creado, actualizado)
  values (s ->> 'endpoint', s #>> '{keys,p256dh}', s #>> '{keys,auth}', p_token, m.id, u.id, left(p_b ->> 'ua', 300), true, rodar.ahora(), rodar.ahora())
  on conflict (endpoint) do update set p256dh = excluded.p256dh, auth = excluded.auth, token = excluded.token, movil_id = excluded.movil_id,
    usuario_id = excluded.usuario_id, ua = excluded.ua, activa = true, actualizado = excluded.actualizado;
  return jsonb_build_object('ok', true);
end $$;

-- Edge Function "push": toma un aviso de la cola (con el secreto compartido) y después informa las suscripciones vencidas
create or replace function public.r_push_tomar(p_token text default null, p_q jsonb default '{}', p_b jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = rodar, public, extensions as $$
declare c jsonb := rodar.cfg('push', '{}'); q rodar.push_cola;
begin
  if coalesce(c ->> 'secreto', '') = '' or p_b ->> 'secreto' is distinct from c ->> 'secreto' then raise exception 'No autorizado'; end if;
  update rodar.push_cola set estado = 'enviando' where id = (p_b ->> 'id')::bigint and estado = 'pendiente' returning * into q;
  if q.id is null then return jsonb_build_object('nada', true); end if;
  return jsonb_build_object('msg', q.msg, 'subs', q.subs, 'publica', c ->> 'publica', 'privada', c ->> 'privada', 'sujeto', coalesce(c ->> 'sujeto', 'mailto:soporte@remisestoque.com'));
end $$;
create or replace function public.r_push_resultado(p_token text default null, p_q jsonb default '{}', p_b jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = rodar, public, extensions as $$
declare c jsonb := rodar.cfg('push', '{}');
begin
  if coalesce(c ->> 'secreto', '') = '' or p_b ->> 'secreto' is distinct from c ->> 'secreto' then raise exception 'No autorizado'; end if;
  update rodar.push_cola set estado = 'enviado', resultado = p_b -> 'resultado' where id = (p_b ->> 'id')::bigint;
  update rodar.push_subs set activa = false, actualizado = rodar.ahora()
    where endpoint in (select jsonb_array_elements_text(coalesce(p_b -> 'vencidas', '[]'::jsonb)));
  return jsonb_build_object('ok', true);
end $$;

grant execute on function public.r_cond_push(text, jsonb, jsonb), public.r_push_tomar(text, jsonb, jsonb), public.r_push_resultado(text, jsonb, jsonb) to anon, authenticated;
alter function rodar.push_enviar(jsonb, jsonb, text) set search_path = rodar, public, extensions;
alter function rodar.push_evento(text, text, jsonb) set search_path = rodar, public, extensions;
alter function rodar.emit(text, text, jsonb) set search_path = rodar, public, extensions;
notify pgrst, 'reload schema';
